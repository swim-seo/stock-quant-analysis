CREATE TABLE IF NOT EXISTS ticker_aliases (
  id         SERIAL PRIMARY KEY,
  ticker     VARCHAR(20)  NOT NULL UNIQUE,
  stock_name VARCHAR(100) NOT NULL,
  sector     VARCHAR(50),
  aliases    JSONB        NOT NULL DEFAULT '[]'
);

CREATE INDEX IF NOT EXISTS idx_ticker_aliases_stock_name ON ticker_aliases (stock_name);
CREATE INDEX IF NOT EXISTS idx_ticker_aliases_sector     ON ticker_aliases (sector);
-- GIN index for searching inside aliases array
CREATE INDEX IF NOT EXISTS idx_ticker_aliases_aliases    ON ticker_aliases USING GIN (aliases);

ALTER TABLE ticker_aliases ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "public read" ON ticker_aliases;
CREATE POLICY "public read" ON ticker_aliases FOR SELECT USING (true);

